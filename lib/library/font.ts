/** Turn a string into a character map, one glyph at a time with a 1px gap.
 *  Unknown characters become a space rather than a missing-glyph box: this is
 *  signage, and a hole in a word is worse than a narrow one. */
export function textArt(str: string, key = "#"): string[] {
  const rows = ["", "", "", "", ""];
  for (const ch of str.toUpperCase()) {
    const g = G[ch];
    for (let r = 0; r < 5; r++) rows[r] += (g ? g[r].replaceAll("#", key) : "...") + ".";
  }
  return rows;
}

/** Width in pixels of a string set in this font. */
export const textW = (str: string) => str.length * 4;
